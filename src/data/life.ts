// 统计数据
export const getLifeStats = () => {
    const moments = getLifeMoments()
    return {
        totalMoments: moments.length,
        totalPhotos: moments.reduce((sum, moment) => sum + moment.images.length, 0)
    }
}

export const getLifeMomentsSorted = (): LifeMoment[] => {
    return getLifeMoments().sort((a, b) => {
        return new Date(b.createTime).getTime() - new Date(a.createTime).getTime()
    })
}